/** أسماء الأجزاء بمطالعها المشهورة */
export const JUZ_NAMES = [
  'الم', 'سيقول', 'تلك الرسل', 'لن تنالوا', 'والمحصنات', 'لا يحب الله', 'وإذا سمعوا', 'ولو أننا', 'قال الملأ', 'واعلموا',
  'يعتذرون', 'وما من دابة', 'وما أبرئ', 'ربما', 'سبحان', 'قال ألم', 'اقترب', 'قد أفلح', 'وقال الذين', 'أمّن خلق',
  'اتل ما أوحي', 'ومن يقنت', 'وما لي', 'فمن أظلم', 'إليه يُرد', 'حم', 'قال فما خطبكم', 'قد سمع', 'تبارك', 'عمّ',
];

const ORDINALS = [
  'الأول', 'الثاني', 'الثالث', 'الرابع', 'الخامس', 'السادس', 'السابع', 'الثامن', 'التاسع', 'العاشر',
];
const TENS = ['', 'عشر', 'العشرون', 'الثلاثون'];
const UNITS_F = ['', 'الحادي', 'الثاني', 'الثالث', 'الرابع', 'الخامس', 'السادس', 'السابع', 'الثامن', 'التاسع'];

/** «الجزء الثامن والعشرون» */
export function juzOrdinal(n: number): string {
  if (n <= 10) return `الجزء ${ORDINALS[n - 1]}`;
  if (n < 20) return `الجزء ${UNITS_F[n - 10]} عشر`;
  const t = Math.floor(n / 10);
  const u = n % 10;
  return u === 0 ? `الجزء ${TENS[t]}` : `الجزء ${UNITS_F[u]} و${TENS[t]}`;
}
