/**
 * مفتاح البحث في نص المصحف: يتجاهل التشكيل وعلامات الضبط، ويحذف الألف
 * بصوره كلها فيطابق «الصلاة» رسمَ «ٱلصَّلَوٰة» و«الطاغوت» رسمَ «ٱلطَّـٰغُوت»،
 * ويوحّد الياء والتاء المربوطة. يُطبَّق على النص (في scripts/build-quran-data.mjs)
 * وعلى ما يكتبه المستخدم بالدالة نفسها.
 */
export function searchKey(text: string): string {
  return text
    .replace(/وٰ/g, 'ا')
    .replace(/[ؐ-ًؚ-ٰٟۖ-ۭ࣓-ࣿـ]/g, '')
    .replace(/[آأإاٱ-ٳ]/g, '')
    .replace(/ى/g, 'ي')
    .replace(/ة/g, 'ه')
    .replace(/\s+/g, ' ')
    .trim();
}
